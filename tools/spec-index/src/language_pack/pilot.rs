//! The 20-card cross-language pilot spread. Declarative,
//! static data: every field is authored here and the generator ([`super::generate`])
//! turns each row into a schema-valid card plus its example records.
//!
//! Constraints encoded by construction: at least four cards carry composed
//! multi-file examples (#2 import, #8 part-usage, #16 satisfaction, #17
//! verification); at least four reach real semantic validation via a negative
//! that trips a specific `S0xx` rule (#1 S001, #10 S108, #13 S068, #15 S060).
//! Example source bytes live only here / in the exported `examples/` tree,
//! never inside card prose. All snippets were verified
//! against the tree-sitter parser + resolver before being recorded.

/// Single-file positive example.
pub struct Pos {
    pub slug: &'static str,
    pub source: &'static str,
    /// ElementKinds that must be present in the lowered ModelGraph.
    pub kinds: &'static [&'static str],
    /// Whether the positive must fully resolve (no unresolved references).
    pub must_resolve: bool,
    pub runtime: &'static str,
}

/// Single-file negative example with its one intended fault.
pub struct Neg {
    pub slug: &'static str,
    pub source: &'static str,
    pub phase: &'static str,          // parse | resolve | validate
    pub mutation: &'static str,       // schema mutation_class enum
    pub parse_failure_class: Option<&'static str>,
    pub diagnostic_category: Option<&'static str>,
    pub diagnostic_code: Option<&'static str>, // e.g. "S060"
}

/// Composed multi-file example.
pub struct Composed {
    pub slug: &'static str,
    /// (name, role, source); role ∈ primary | supporting | library-stub.
    pub files: &'static [(&'static str, &'static str, &'static str)],
    pub kinds: &'static [&'static str],
    pub must_resolve: bool,
}

/// One pilot card definition.
pub struct PilotCard {
    pub id: &'static str,
    pub authority: &'static str, // kerml | sysml
    pub grammar: &'static str,   // kerml | sysml | expressions
    pub rule: &'static str,
    pub language: &'static str, // KerML | SysML | Expressions
    pub title: &'static str,
    pub summary: &'static str,
    pub category: &'static [&'static str],
    pub keywords_extra: &'static [&'static str],
    pub semantic_types: &'static [&'static str],
    pub clause: &'static str,
    pub document: &'static str, // SysML | KerML
    pub pos: Pos,
    pub neg: Neg,
    pub composed: Option<Composed>,
    /// Additional `(grammar, rule)` provenance for a cross-grammar merge-set
    /// card: the same-named, IR-equivalent production is declared
    /// in more than one grammar, so both source rows are recorded as normative
    /// rules and as the denominator record's `merged_from` edges. Empty for the
    /// common single-grammar card.
    pub extra_rules: &'static [(&'static str, &'static str)],
}

const UNRESOLVED: Option<&str> = Some("unresolved-reference");

/// A cross-grammar *divergent* concept (split-set): the same rule
/// name is declared with IR-divergent bodies in both grammars, so it mints TWO
/// authority-scoped cards (`kerml.<facet>.<slug>` + `sysml.<facet>.<slug>`),
/// each carrying only its own grammar's IR, cross-linked via `related_cards`.
/// The clause + examples are shared (the abstract-syntax relationship is one
/// concept realized by two concrete syntaxes).
pub struct SplitPair {
    pub facet: &'static str,
    pub slug: &'static str,
    /// Rule name, identical in both grammars (the divergence is in the body).
    pub rule: &'static str,
    pub title: &'static str,
    pub summary: &'static str,
    pub category: &'static [&'static str],
    pub keywords_extra: &'static [&'static str],
    pub semantic_types: &'static [&'static str],
    pub clause: &'static str,
    pub document: &'static str,
    pub pos: Pos,
    pub neg: Neg,
}

